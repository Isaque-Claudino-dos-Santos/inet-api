package com.inet.resources;

public class UserStoreResource {
    Boolean success = true;
    String name;
    String email;
    String type;

    public Boolean getSuccess() {
        return success;
    }

    public String getName() {
        return name;
    }

    public String getEmail() {
        return email;
    }

    public String getType() {
        return type;
    }
}
